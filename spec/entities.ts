export type EntityName =
  | 'client' | 'lead' | 'interaction' | 'opportunity' | 'proposal' | 'sale'
  | 'payment' | 'expense' | 'marketingCampaign' | 'salesperson' | 'consultant'
  | 'project' | 'task' | 'feedback';

export interface AuditEvent extends SampleFlag {
  id: AuditEventID;                   // PK
  entity: EntityName;                 // which table
  entityId: string;                   // FK→ that entity's id
  action: 'create' | 'update' | 'delete' | 'status_change' | 'convert';
  field: string | null;               // changed field (for update)
  before: string | null;              // prior value (stringified)
  after: string | null;               // new value (stringified)
  actor: string;                      // user/salesperson who acted (or 'foundry')
  timestamp: ISODate;                 // when
}

