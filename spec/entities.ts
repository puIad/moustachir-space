/* ========================================================================== *
 *  1. Client   (REAL base: dim_client + dim_client_pii)
 * ========================================================================== */
export interface Client extends SampleFlag {
  id: ClientID;                       // REAL  dim_client.client_id (PK)
  type: ClientType;                   // DERIVED from project_stage / purchase history
  // --- identity (REAL-PII: restricted, only hydrated for authorized views) ---
  fullName?: string;                  // REAL-PII dim_client_pii.full_name
  email?: string;                     // REAL-PII dim_client_pii.email
  phone?: string;                     // REAL-PII dim_client_pii.phone_e164
  // --- firmographics ---
  companyName: string | null;         // REAL  dim_client.company_name
  industry: string | null;            // REAL  dim_client.sector
  country: string | null;             // SIM   (warehouse has no country; foundry fills, DZ-weighted)
  city: string | null;                // SIM
  address: string | null;             // SIM
  position: string | null;            // SIM   contact role/title
  companySize: string | null;         // SIM   e.g. "1-10" | "11-50" | "51-200" | "200+"
  // --- acquisition (REAL) ---
  sourceAcquisition: Channel;         // REAL  dim_client.channel
  acquisitionCampaign: string | null; // SIM   campaign name (links MarketingCampaign)
  acquisitionChannel: Channel;        // REAL  alias of channel
  responsibleSalespersonId: SalespersonID | null; // REAL dim_client.salesman (FK→Salesperson)
  // --- routing (REAL) ---
  branchKey: BranchKey;               // REAL  dim_client.branch
  serviceLine: ServiceLine;           // REAL  dim_client.service_line
  branchConfidence: 'real' | 'inferred'; // REAL dim_client.branch_confidence
  // --- lifecycle dates ---
  firstContactDate: ISODate;          // REAL  dim_client.first_seen
  firstPurchaseDate: ISODate | null;  // SIM
  lastPurchaseDate: ISODate | null;   // SIM
  lastActivityDate: ISODate | null;   // SIM
  status: string;                     // DERIVED current lifecycle status
  // --- value metrics (DERIVED / SIM) ---
  lifetimeRevenue: MoneyDA;           // DERIVED Σ Sale.amount for client
  lifetimeProfit: MoneyDA;            // DERIVED Σ Sale.margin for client
  numberPurchases: number;            // DERIVED count(Sale)
  numberCalls: number;                // DERIVED count(Interaction type=Call)
  numberMeetings: number;             // DERIVED count(Interaction type=Meeting)
  numberMessages: number;             // DERIVED count(Interaction type∈{WhatsApp,Email})
  customerScore: number;              // DERIVED ML score 0–100 (foundry)
  churnRiskScore: number;             // DERIVED ML score 0–1 (foundry)
  // --- data-quality provenance (REAL) ---
  consentFlag: boolean;               // REAL  dim_client.consent_flag (Loi 18-07)
  isMerged: boolean;                  // REAL  dim_client.is_merged
  needsReview: boolean;               // REAL  dim_client.needs_review
  sourceCount: number;                // REAL  dim_client.source_count
}

