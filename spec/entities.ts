/**
 * spec/entities.ts — CANONICAL ENTITY CONTRACT (Step 0, LOCKED)
 * ----------------------------------------------------------------------------
 * The single typed source of truth for every entity in the Moustachir BI
 * platform. The Python foundry (Step 2) emits rows matching these shapes; the
 * Dexie store (Step 3) types its tables from them; screens (Steps 4–8) read them.
 * Imported everywhere, redefined nowhere.
 *
 * Sources: NEW Implementation.docx ("Identify the data"), warehouse/*.csv headers,
 * kpi_summary.json, IMPLEMENTATION_ROADMAP.md (locked decisions).
 *
 * PROVENANCE CONVENTION
 *   REAL      — value comes from the warehouse star schema (Axe2/Axe3 acquisition data).
 *   REAL-PII  — real but lives only in restricted dim_client_pii (Loi 18-07 isolation).
 *   SIM       — synthetic, generated by the foundry; the row carries isSample = true.
 *   DERIVED   — computed from other fields (by foundry at build time or by lib/kpis.ts).
 * Each entity that can be wholly synthetic carries `isSample: boolean`
 * (true ⇒ projection; UI shows the "PROJECTION — sample data" badge).
 */

